#!/usr/bin/env node
/*
 * Page Object Model stub generator.
 *
 * Reads an inventory-<Module>.json produced by ui-inventory-scanner.js and
 * emits one C# Page Object class per component, with strongly-typed
 * Playwright ILocator properties for every selector found.
 *
 * Selector preference per element:
 *   1. data-testid  →  `[data-testid='X']`
 *   2. id           →  `#X`        (scoped via parent component when collision)
 *   3. name         →  `[name='X']`
 *   4. aria-label   →  `[aria-label='X']`
 *   5. placeholder  →  `[placeholder='X']`
 *
 * Usage:
 *   node pom-generator.js <inventoryJson> <outputDir> <namespace>
 */
const fs = require("fs");
const path = require("path");

const inventoryJson = process.argv[2];
const outputDir     = process.argv[3];
const namespace     = process.argv[4] || "MNPS.WorkFlow.WebPages.Generated";

if (!inventoryJson || !outputDir) {
    console.error("Usage: node pom-generator.js <inventoryJson> <outputDir> [namespace]");
    process.exit(2);
}

const data = JSON.parse(fs.readFileSync(inventoryJson, "utf8"));
if (!fs.existsSync(outputDir)) fs.mkdirSync(outputDir, { recursive: true });

// Group elements by component
const byComponent = {};
for (const el of data.elements) {
    (byComponent[el.component] ||= []).push(el);
}

// PascalCase a property name from a raw selector value
function toPropertyName(raw) {
    let s = raw
        .replace(/[^A-Za-z0-9 _-]/g, "")        // strip punctuation
        .replace(/[-_ ]+/g, " ")                 // unify separators
        .trim()
        .split(" ")
        .map(w => w.charAt(0).toUpperCase() + w.slice(1))
        .join("");
    if (/^\d/.test(s)) s = "_" + s;
    return s || "Element";
}

// Convert "Enter Permission Name" → "EnterPermissionName"
function placeholderToProp(raw) {
    return toPropertyName(raw);
}

// Convert selector → CSS string for ILocator
function toCssSelector(el) {
    const v = el.value.replace(/'/g, "\\'");
    switch (el.kind) {
        case "data-testid": return `[data-testid='${v}']`;
        case "id":          return `#${el.value.replace(/[^A-Za-z0-9_-]/g, "")}`;
        case "name":        return `[name='${v}']`;
        case "aria-label":  return `[aria-label='${v}']`;
        case "placeholder": return `[placeholder='${v}']`;
        case "role":        return `[role='${v}']`;
        default:            return `[data-testid='${v}']`;
    }
}

// For each element pick the BEST single selector (highest-weight kind).
// One property per logical element — if a field has data-testid and a placeholder,
// emit data-testid only (cleaner Page Object).
function dedupeByBestSelector(elements) {
    // Group by approx-target. Without DOM context we treat (kind+value) as the unit,
    // but collapse same value across different kinds (e.g. id="x" + placeholder for x).
    // Heuristic: if two elements on adjacent lines share a placeholder/id/data-testid,
    // they're the same field — keep the highest-weight one.
    const sorted = elements.slice().sort((a, b) => a.line - b.line || b.weight - a.weight);
    const kept = [];
    let lastLine = -10;
    let lastKept = null;
    for (const el of sorted) {
        if (lastKept && Math.abs(el.line - lastLine) <= 3) {
            // Same field cluster — keep higher weight
            if (el.weight > lastKept.weight) {
                kept[kept.length - 1] = el;
                lastKept = el;
            }
            lastLine = el.line;
            continue;
        }
        kept.push(el);
        lastKept = el;
        lastLine = el.line;
    }
    return kept;
}

// Generate one .cs file per component
let totalProps = 0;
const generated = [];

for (const [component, allEls] of Object.entries(byComponent)) {
    const els = dedupeByBestSelector(allEls);
    const usedNames = new Set();

    const lines = [];
    lines.push(`// <auto-generated />`);
    lines.push(`// Generated from inventory: ${path.basename(inventoryJson)}`);
    lines.push(`// Source component: ${component}`);
    lines.push(`// File: ${els[0]?.file ?? "(unknown)"}`);
    lines.push(`// Elements: ${els.length} (deduped from ${allEls.length} raw matches)`);
    lines.push(`// DO NOT EDIT BY HAND — re-run pom-generator.js after UI changes.`);
    lines.push(``);
    lines.push(`using Microsoft.Playwright;`);
    lines.push(``);
    lines.push(`namespace ${namespace};`);
    lines.push(``);
    lines.push(`/// <summary>Page object for the <c>${component}</c> component.</summary>`);
    lines.push(`public sealed class ${component}Page`);
    lines.push(`{`);
    lines.push(`    private readonly IPage _page;`);
    lines.push(`    public ${component}Page(IPage page) { _page = page; }`);
    lines.push(``);

    for (const el of els) {
        // Build a property name from the selector value
        let baseName;
        if (el.kind === "placeholder") baseName = placeholderToProp(el.value);
        else                            baseName = toPropertyName(el.value);

        // Ensure uniqueness within this class
        let name = baseName;
        let i = 2;
        while (usedNames.has(name)) name = `${baseName}${i++}`;
        usedNames.add(name);

        const css = toCssSelector(el);
        const collisionNote = el.isUnique
            ? "globally unique"
            : `WARNING: value reused ${el.globalCount}x — scope to parent if needed`;

        lines.push(`    /// <summary>${component}: ${el.kind} = "${el.value}" (line ${el.line}) — ${collisionNote}.</summary>`);
        lines.push(`    public ILocator ${name} => _page.Locator("${css}");`);
        lines.push(``);
        totalProps++;
    }
    lines.push(`}`);

    const outFile = path.join(outputDir, `${component}Page.cs`);
    fs.writeFileSync(outFile, lines.join("\r\n"));
    generated.push({ component, file: outFile, propertyCount: els.length });
}

console.log("");
console.log("POM Stub Generator");
console.log("==================");
console.log(`Inventory:    ${inventoryJson}`);
console.log(`Output dir:   ${outputDir}`);
console.log(`Namespace:    ${namespace}`);
console.log(`Components:   ${generated.length}`);
console.log(`Properties:   ${totalProps}`);
console.log("");
for (const g of generated.sort((a, b) => b.propertyCount - a.propertyCount).slice(0, 15)) {
    console.log(`  ${g.component.padEnd(40)} ${String(g.propertyCount).padStart(4)} props`);
}
